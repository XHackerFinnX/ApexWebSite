CREATE TABLE IF NOT EXISTS order_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','running','done','blocked')),
    attempts INTEGER NOT NULL DEFAULT 0,
    due_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_at TIMESTAMPTZ,
    lease_token UUID,
    payload JSONB NOT NULL DEFAULT '{}',
    error TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(order_id,kind)
);
CREATE INDEX IF NOT EXISTS order_jobs_due ON order_jobs(state,due_at);
CREATE INDEX IF NOT EXISTS orders_visible_created ON orders(created_at DESC,id DESC) WHERE deleted_at IS NULL;
CREATE TABLE IF NOT EXISTS payment_events (
    digest TEXT PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES orders(id),
    kind TEXT NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Existing pending payments need reconciliation. Historical paid orders are not
-- backfilled into the external webhook or shipment queues.
INSERT INTO order_jobs(order_id,kind,due_at)
SELECT id,'payment_sync',now()+interval '90 seconds' FROM orders
WHERE status NOT IN ('CONFIRMED','REFUNDED','REVERSED','CANCELED','REJECTED','DEADLINE_EXPIRED')
ON CONFLICT(order_id,kind) DO NOTHING;
